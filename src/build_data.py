def shishen(day_gan, other_gan):
    me, other = GAN_WX[day_gan], GAN_WX[other_gan]
    same = GAN_YY[day_gan] == GAN_YY[other_gan]
    if other == me:
        return "比肩" if same else "劫财"
    if SHENG[me] == other:                 # 我生
        return "食神" if same else "伤官"
    if KE[me] == other:                   # 我克
        return "偏财" if same else "正财"
    if BEI_KE[me] == other:               # 克我
        return "七杀" if same else "正官"
    if BEI_SHENG[me] == other:            # 生我
        return "偏印" if same else "正印"
    raise ValueError((day_gan, other_gan))


